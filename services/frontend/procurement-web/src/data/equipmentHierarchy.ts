export function getUnitsForMachine(machine: string): string[] {
  const units = EQUIPMENT_HIERARCHY[machine];
  if (!units) return [];
  return Object.keys(units).sort();
}

export function getAssembliesForUnit(machine: string, unit: string): string[] {
  const units = EQUIPMENT_HIERARCHY[machine];
  if (!units || !units[unit]) return [];
  return units[unit].slice().sort();
}

